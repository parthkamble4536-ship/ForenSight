"""
Comprehensive forensic data contracts and Pydantic schemas for ForenSight.
"""

from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class HashResult(BaseModel):
    """Cryptographic hash calculation results for an evidence artifact."""

    sha256: str = Field(description="SHA-256 cryptographic digest in lowercase hex")
    sha1: str = Field(description="SHA-1 cryptographic digest in lowercase hex")
    md5: str = Field(description="MD5 cryptographic digest in lowercase hex")
    size_bytes: int = Field(ge=0, description="Exact file size in bytes")


class EvidenceRecord(BaseModel):
    """Metadata record for an ingested evidence item stored in the vault."""

    evidence_id: str = Field(description="Unique UUIDv4 identifying this evidence item")
    case_id: Optional[str] = Field(default=None, description="Associated investigation case UUID")
    original_filename: str = Field(description="Original untrusted filename as provided by user")
    sanitized_filename: str = Field(description="Sanitized version of original filename")
    storage_path: str = Field(description="Absolute filesystem path to the stored UUID evidence file")
    hashes: HashResult = Field(description="Cryptographic hashes computed during ingestion")
    stored_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of ingestion",
    )
    is_read_only: bool = Field(default=True, description="Filesystem read-only protection flag")


class IntegrityCheckResult(BaseModel):
    """Result of an evidence integrity verification audit."""

    evidence_id: str = Field(description="Evidence item identifier")
    is_valid: bool = Field(description="True if all hashes, file size, and containment checks pass")
    is_path_safe: bool = Field(description="True if evidence path is confirmed strictly inside vault")
    expected_sha256: str = Field(description="Reference SHA-256 recorded at ingestion")
    computed_sha256: str = Field(description="Live computed SHA-256 of stored evidence file")
    expected_sha1: str = Field(description="Reference SHA-1 recorded at ingestion")
    computed_sha1: str = Field(description="Live computed SHA-1 of stored evidence file")
    expected_md5: str = Field(description="Reference MD5 recorded at ingestion")
    computed_md5: str = Field(description="Live computed MD5 of stored evidence file")
    expected_size_bytes: int = Field(description="Reference file size recorded at ingestion")
    computed_size_bytes: int = Field(description="Live computed file size in bytes")
    checked_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp when audit was performed",
    )
    details: str = Field(default="", description="Forensic audit notes or discrepancy details")


class FindingSeverity(str, Enum):
    """Standardized severity classification for forensic triage findings."""

    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ConfidenceLevel(str, Enum):
    """Confidence rating of an analytical observation or detection."""

    CONFIRMED = "CONFIRMED"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INCONCLUSIVE = "INCONCLUSIVE"


class IOCType(str, Enum):
    """Indicator of Compromise (IOC) types recognized by ForenSight."""

    IPV4 = "IPV4"
    IPV6 = "IPV6"
    URL = "URL"
    DOMAIN = "DOMAIN"
    EMAIL = "EMAIL"
    FILE_PATH = "FILE_PATH"
    REGISTRY_KEY = "REGISTRY_KEY"
    HASH_MD5 = "HASH_MD5"
    HASH_SHA1 = "HASH_SHA1"
    HASH_SHA256 = "HASH_SHA256"


class Finding(BaseModel):
    """Individual explainable triage finding generated by static analysis rules."""

    finding_id: Optional[str] = Field(default=None, description="Unique finding UUID")
    rule_id: str = Field(description="Unique rule code, e.g. PE-001, PDF-003, DOCX-002, ARCH-001")
    rule_version: str = Field(default="1.0.0", description="Rule definition version")
    category: str = Field(description="Functional category, e.g. PACKING, SCRIPT_EXECUTION, ANOMALY, DECEPTION")
    title: str = Field(description="Brief human-readable summary of the indicator")
    description: str = Field(description="Detailed explanation of what was detected and why it is significant")
    severity: FindingSeverity = Field(description="Finding severity level")
    confidence: ConfidenceLevel = Field(default=ConfidenceLevel.HIGH, description="Analytic confidence level")
    score_impact: int = Field(default=0, ge=0, le=100, description="Contribution to total risk score")
    analyzer_name: str = Field(default="", description="Analyzer module name that produced the finding")
    analyzer_version: str = Field(default="", description="Analyzer module version")
    evidence_source: str = Field(default="", description="Specific parser or subsystem that identified finding")
    evidence_reference: Optional[str] = Field(default=None, description="Evidence UUID or artifact reference")
    object_reference: Optional[str] = Field(default=None, description="Relevant section, object number, or XML part")
    offset: Optional[int] = Field(default=None, ge=0, description="Byte offset in source artifact if known")
    evidence_snippet: Optional[str] = Field(default=None, description="Relevant byte offset, string, or header excerpt")
    explanation: Optional[str] = Field(default=None, description="Forensic explanation of risk and potential false positives")
    mitre_technique: Optional[str] = Field(default=None, description="Associated MITRE ATT&CK technique if applicable")
    detected_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of detection",
    )


class IOCRecord(BaseModel):
    """Extracted Indicator of Compromise with defanging, context, and confidence."""

    ioc_type: IOCType = Field(description="Classification of the indicator")
    value: str = Field(description="Raw indicator value extracted from artifact")
    defanged_value: str = Field(description="Safe defanged representation (e.g. hxxp://, [.] )")
    context: Optional[str] = Field(default=None, description="Surrounding string or structural location")
    offset: Optional[int] = Field(default=None, ge=0, description="Byte offset in source artifact if known")
    confidence: ConfidenceLevel = Field(default=ConfidenceLevel.HIGH, description="Extraction confidence")
    occurrences: int = Field(default=1, ge=1, description="Number of times indicator appears in evidence")


class RiskScore(BaseModel):
    """Aggregated explainable risk assessment and triage verdict."""

    score: int = Field(ge=0, le=100, description="Normalized risk score from 0 to 100")
    verdict: str = Field(description="Human-readable triage verdict: Benign, Low Risk, Suspicious, High Risk")
    confidence: ConfidenceLevel = Field(default=ConfidenceLevel.HIGH, description="Overall confidence")
    severity_counts: Dict[str, int] = Field(
        default_factory=dict,
        description="Count of findings broken down by severity",
    )
    summary: str = Field(description="Forensic summary explaining the risk score rationale")
    rule_contributions: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Itemized list of findings and their individual contribution to score",
    )
    caveat: str = Field(
        default="Static triage assessment based on observed file structures and heuristic indicators; does not confirm malicious execution behavior.",
        description="Standard forensic disclaimer",
    )


class EvidenceMetadata(BaseModel):
    """High-level file identification and general metadata."""

    file_size_bytes: int = Field(ge=0, description="File size in bytes")
    identified_type: str = Field(description="Identified primary category (PE, PDF, DOCX, DOCM, EML, MSG, ZIP, IMAGE, TXT, LOG, UNKNOWN)")
    mime_type: str = Field(description="Detected MIME type based on magic bytes")
    declared_extension: str = Field(description="Extension declared in original filename")
    is_extension_mismatch: bool = Field(
        default=False,
        description="True if magic bytes contradict the declared file extension (masquerade alert)",
    )
    magic_match_details: Optional[str] = Field(default=None, description="Description from magic byte database")
    entropy: float = Field(ge=0.0, le=8.0, description="Overall Shannon entropy of file contents")


class EvidenceManifest(BaseModel):
    """Cryptographic manifest documenting an evidence artifact's acquisition state."""

    manifest_id: str = Field(description="Unique manifest UUID")
    evidence_id: str = Field(description="Referenced evidence UUID")
    case_id: Optional[str] = Field(default=None, description="Associated case UUID")
    original_filename: str = Field(description="Original untrusted filename")
    hashes: HashResult = Field(description="Recorded cryptographic hashes")
    file_type: str = Field(description="Identified file format")
    acquired_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Acquisition UTC timestamp",
    )
    signature: Optional[str] = Field(default=None, description="Ed25519 digital signature of manifest data")
    public_key_fingerprint: Optional[str] = Field(default=None, description="Fingerprint of signing key")


class ChainOfCustodyEvent(BaseModel):
    """Immutable audit trail record documenting actions taken on evidence."""

    event_id: str = Field(description="Unique audit event UUID")
    evidence_id: str = Field(description="Associated evidence UUID")
    case_id: Optional[str] = Field(default=None, description="Associated case UUID")
    event_type: str = Field(description="Action: INGEST, INTEGRITY_AUDIT, ANALYSIS_EXECUTION, REPORT_EXPORT")
    actor: str = Field(default="system", description="User or automated subsystem performing action")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of the event",
    )
    details: str = Field(description="Detailed narrative of action taken")
    previous_event_hash: Optional[str] = Field(default=None, description="Hash of predecessor audit event for cryptographic chaining")
    event_hash: str = Field(description="SHA-256 digest of this event record")


class TimelineEventType(str, Enum):
    """Source classification of a timeline timestamp."""

    FILE_SYSTEM = "FILE_SYSTEM"
    METADATA = "METADATA"
    COMPILE_TIME = "COMPILE_TIME"
    ARCHIVE_ENTRY = "ARCHIVE_ENTRY"
    EMAIL_RECEIVED = "EMAIL_RECEIVED"
    INGESTION = "INGESTION"
    ANALYSIS = "ANALYSIS"


class TimelineEvent(BaseModel):
    """Discrete chronological event associated with an evidence artifact."""

    event_id: str = Field(description="Unique timeline event UUID")
    evidence_id: str = Field(description="Source evidence UUID")
    timestamp: datetime = Field(description="Normalized UTC timestamp")
    original_timestamp: Optional[str] = Field(
        default=None,
        description="Original unparsed timestamp string preserved from artifact metadata if available",
    )
    timestamp_type: TimelineEventType = Field(description="Source classification of timestamp")
    source: str = Field(description="Source field or structure (e.g. PE Header, EXIF DateTimeOriginal, Ingest)")
    description: str = Field(description="Human-readable description of event")
    confidence: ConfidenceLevel = Field(default=ConfidenceLevel.HIGH, description="Timestamp reliability confidence")


class RelationshipType(str, Enum):
    """Classification of an evidence-to-evidence correlation."""

    SHARED_HASH = "SHARED_HASH"
    SHARED_IOC = "SHARED_IOC"
    EMBEDDED_FILE = "EMBEDDED_FILE"
    SHARED_AUTHOR = "SHARED_AUTHOR"
    ARCHIVE_CONTAINER = "ARCHIVE_CONTAINER"
    EMAIL_ATTACHMENT = "EMAIL_ATTACHMENT"
    TIMESTAMP_CLUSTERING = "TIMESTAMP_CLUSTERING"


class EvidenceRelationship(BaseModel):
    """Correlated relationship between two evidence artifacts in a case."""

    relationship_id: str = Field(description="Unique relationship UUID")
    case_id: str = Field(description="Case context UUID")
    source_evidence_id: str = Field(description="Source evidence UUID")
    target_evidence_id: str = Field(description="Target evidence UUID")
    relationship_type: RelationshipType = Field(description="Category of correlation")
    reason: str = Field(description="Detailed explanation of correlation")
    shared_value: Optional[str] = Field(default=None, description="Specific shared value (IOC, hash, author)")
    weight: float = Field(default=1.0, ge=0.0, le=1.0, description="Relationship significance weight")


class AnalysisResult(BaseModel):
    """Master container aggregating all analysis outputs for an evidence artifact."""

    evidence: EvidenceRecord
    metadata: EvidenceMetadata
    risk: RiskScore
    findings: List[Finding] = Field(default_factory=list)
    iocs: List[IOCRecord] = Field(default_factory=list)
    timeline: List[TimelineEvent] = Field(default_factory=list)
    analyzer_details: Dict[str, Any] = Field(
        default_factory=dict,
        description="Specialized structural details from specific analyzers",
    )
    analyzed_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp when analysis completed",
    )
